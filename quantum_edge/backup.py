"""Small portable backup of the experiment (clock, portfolio, fills, strategies) as JSON.
Lab experiments are not included: they are large and are regenerated by a research run."""
from __future__ import annotations

import json
from datetime import datetime
from pathlib import Path

from sqlalchemy import select

from .db import KV, Database, Decision, EquitySnapshot, Fill, Incident, Position, Strategy

TABLES = {"positions": (Position, None), "fills": (Fill, None), "strategies": (Strategy, None),
          "equity": (EquitySnapshot, 3000), "decisions": (Decision, 500), "incidents": (Incident, 500)}
KEYS = ("experiment", "lab_status", "lab_run_id")


def export_state(db: Database) -> dict:
    out = {"version": 1, "kv": {k: db.get(k) for k in KEYS}, "tables": {}}
    with db.session() as s:
        for name, (model, limit) in TABLES.items():
            q = select(model).order_by(model.id.desc())
            rows = list(s.scalars(q.limit(limit) if limit else q))[::-1]
            out["tables"][name] = [
                {c.name: (v.isoformat() if isinstance(v := getattr(r, c.name), datetime) else v)
                 for c in model.__table__.columns} for r in rows]
    return out


def save(db: Database, path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(export_state(db), separators=(",", ":")), encoding="utf-8")
    return path


def restore(db: Database, path: str | Path) -> str:
    """Load a backup into an EMPTY database. Refuses to overwrite an existing experiment."""
    with db.session() as s:
        if s.scalar(select(Fill.id).limit(1)) or s.get(KV, "experiment"):
            return "database already holds an experiment; nothing restored"
    data = json.loads(Path(path).read_text(encoding="utf-8"))
    with db.session() as s:
        for name, (model, _) in TABLES.items():
            dt_cols = {c.name for c in model.__table__.columns if "DateTime" in type(c.type).__name__ or "UTCDateTime" in type(c.type).__name__}
            for row in data["tables"].get(name, []):
                for c in dt_cols:
                    if row.get(c):
                        row[c] = datetime.fromisoformat(row[c])
                s.add(model(**row))
    for k, v in data["kv"].items():
        if v is not None:
            db.set(k, v)
    n = {k: len(v) for k, v in data["tables"].items()}
    return f"restored: {n}"
